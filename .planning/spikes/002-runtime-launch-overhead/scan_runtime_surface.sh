#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
OUT_DIR="$ROOT/.planning/spikes/002-runtime-launch-overhead"
REPORT="$OUT_DIR/surface-report.md"
JSON="$OUT_DIR/surface-report.json"

count_rg() {
  local pattern="$1"
  local path="${2:-$ROOT}"
  rg -n "$pattern" "$path" 2>/dev/null | wc -l | tr -d ' '
}

count_files() {
  find "$1" -type f -name '*.rs' 2>/dev/null | wc -l | tr -d ' '
}

sum_lines() {
  find "$1" -type f -name '*.rs' -print0 2>/dev/null \
    | xargs -0 wc -l 2>/dev/null \
    | awk '$2 != "total" { total += $1 } END { print total + 0 }'
}

top_kernel_files() {
  find "$ROOT/crates" -path '*/src/*.rs' -type f -print0 2>/dev/null \
    | xargs -0 wc -l 2>/dev/null \
    | sort -nr \
    | awk 'NR <= 15 && $2 != "total" { printf "- %s lines: `%s`\n", $1, substr($0, index($0,$2)) }'
}

bench_placeholders="$(rg -n 'benchmark placeholder' "$ROOT/benches" 2>/dev/null || true)"
resident_stubs="$(rg -n 'Placeholder stub' "$ROOT/src/input/resident.rs" "$ROOT/src/output/resident.rs" 2>/dev/null || true)"

kernel_rs_files="$(count_files "$ROOT/crates")"
kernel_rs_lines="$(sum_lines "$ROOT/crates")"
cube_launches="$(count_rg '#\[cube\(launch_unchecked\)\]' "$ROOT/crates")"
plain_cube_helpers="$(count_rg '#\[cube\]' "$ROOT/crates")"
host_launch_calls="$(count_rg 'launch_unchecked::<CpuRuntime>' "$ROOT/src")"
cpu_client_calls="$(count_rg 'cpu_client\(\)' "$ROOT/src")"
create_input_calls="$(count_rg 'create_input_buffer' "$ROOT/src/eval")"
zero_output_calls="$(count_rg 'create_zero_output_buffer' "$ROOT/src/eval")"
readback_calls="$(count_rg 'read_output_buffer' "$ROOT/src/eval")"
resident_stub_count="$(printf '%s\n' "$resident_stubs" | sed '/^$/d' | wc -l | tr -d ' ')"
bench_placeholder_count="$(printf '%s\n' "$bench_placeholders" | sed '/^$/d' | wc -l | tr -d ' ')"

cat > "$REPORT" <<REPORT_EOF
# Runtime Launch Surface Audit

Generated by \`scan_runtime_surface.sh\`.

## Counts

| Signal | Count | Interpretation |
|---|---:|---|
| Rust files under \`crates/\` | $kernel_rs_files | Generated-kernel surface is broad enough that per-entry changes need generation support. |
| Rust lines under \`crates/\` | $kernel_rs_lines | Large generated kernels make manual runtime tuning brittle. |
| Launchable CubeCL kernels in \`crates/\` | $cube_launches | Every entry point has generated launch machinery; launch overhead matters. |
| Plain CubeCL helpers in \`crates/\` | $plain_cube_helpers | Helper reuse exists, but launch entry count remains high. |
| Host \`launch_unchecked::<CpuRuntime>\` calls in \`src/\` | $host_launch_calls | Dispatch is host-launch heavy and should stay centralized. |
| \`cpu_client()\` calls in \`src/\` | $cpu_client_calls | Direct dispatch creates clients inside hot paths. |
| Input upload call sites in \`src/eval\` | $create_input_calls | Direct dispatch re-uploads host input per evaluation. |
| Zero output allocation call sites in \`src/eval\` | $zero_output_calls | Direct dispatch allocates zeroed device output per evaluation. |
| Readback call sites in \`src/eval\` | $readback_calls | Direct dispatch synchronizes/readbacks per requested output field. |
| Resident input/output stubs | $resident_stub_count | Resident execution surface is not implemented yet. |
| Placeholder benchmark files | $bench_placeholder_count | No runtime benchmarks currently measure this path. |

## Largest Generated Kernel Files

$(top_kernel_files)

## Placeholder Benches

\`\`\`text
$bench_placeholders
\`\`\`

## Resident Stubs

\`\`\`text
$resident_stubs
\`\`\`

## Refactor Signals

1. The first runtime optimization should target host orchestration: client reuse, input residency, output buffer reuse, and selective readback.
2. Kernel fusion or math-level rewrites should wait until benchmark coverage proves the host path is no longer dominant.
3. The generated kernel entry surface is large, so runtime changes should be in shared launch/eval layers rather than hand-editing generated kernels.
4. Resident modules and benchmarks already exist as placeholders, making them the natural implementation boundary for a measured refactor.
REPORT_EOF

cat > "$JSON" <<JSON_EOF
{
  "kernel_rs_files": $kernel_rs_files,
  "kernel_rs_lines": $kernel_rs_lines,
  "cube_launch_unchecked_kernels": $cube_launches,
  "plain_cube_helpers": $plain_cube_helpers,
  "host_cpu_launch_calls": $host_launch_calls,
  "cpu_client_calls": $cpu_client_calls,
  "input_upload_call_sites": $create_input_calls,
  "zero_output_call_sites": $zero_output_calls,
  "readback_call_sites": $readback_calls,
  "resident_stub_count": $resident_stub_count,
  "bench_placeholder_count": $bench_placeholder_count
}
JSON_EOF

echo "Wrote $REPORT"
echo "Wrote $JSON"
