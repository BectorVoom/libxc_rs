/// libxc `util.h::xc_cheb_eval` -- Clenshaw recurrence, same operand order.
#[inline]
pub(crate) fn cheb_eval(x: f64, cs: &[f64]) -> f64 {
    let twox = 2.0_f64 * x;
    let (mut b0, mut b1, mut b2) = (0.0_f64, 0.0_f64, 0.0_f64);
    let mut i = cs.len();
    while i > 0 {
        i -= 1;
        b2 = b1;
        b1 = b0;
        b0 = twox * b1 - b2 + cs[i];
    }
    0.5_f64 * (b0 - b2)
}

