/// Evaluate an MGGA functional on the given input, writing results to output.
///
/// Per-functional kernel scalars are hardcoded in each functional's launch
/// helper (B3: no shared `MggaFunctionalParams` struct). If a functional's
/// kernel takes scalar arguments whose libxc ext_params defaults have not yet
/// been wired, this function returns `Err(UnsupportedFunctional)` — the match
/// arm is listed so the functional is routable in principle, but the dispatch
/// short-circuits until follow-up plans add the default values.
///
/// # Errors
/// * `UnsupportedDerivativeOrder` if `order == Exc` for a _vxc-only
///   functional like `MggaXTb09`, or for orders >= Fxc (this layer
///   wires only Exc and Vxc).
/// * `UnsupportedFunctional` if the requested functional's per-functional
///   scalar defaults have not yet been wired, or if spin is Polarized
///   (pol dispatch deferred pending pol-kernel translation fixes).
/// * `KernelLaunchFailed` on CubeCL launch failure.
pub fn dispatch_mgga(
    functional: MggaFunctional,
    input: &MggaInput,
    order: DerivativeOrder,
    output: &mut MggaOutput,
    params: &dyn FunctionalParams,
    thresholds: &Thresholds,
) -> Result<(), LibxcRsError> {
    // `params` is currently unused by MGGA dispatch: the routed MGGA
    // functionals that launch with ext_params use hardcoded libxc 7.0.0
    // defaults at the launch site (matching the C oracle). The trait-object
    // parameter is reserved for per-arm downcasts when per-functional scalar
    // wiring lands.
    let _ = params;
    // 1. Validate functional can satisfy the requested order (W5 — filesystem-driven has_exc).
    if order == DerivativeOrder::Exc && !functional.has_exc() {
        return Err(LibxcRsError::UnsupportedDerivativeOrder {
            id: functional.to_id(),
            order,
            max: DerivativeOrder::Vxc,
        });
    }

    let np = input.np();
    let spin = input.spin();
    let dims = Dimensions::mgga(spin);

    // 2. Zero all 70 caller output buffers.
    macro_rules! zero_field { ($field:ident) => {
        if let Some(ref mut b) = output.$field { b.fill(0.0); }
    }; }
    zero_field!(zk);
    zero_field!(vrho); zero_field!(vsigma); zero_field!(vlapl); zero_field!(vtau);
    zero_field!(v2rho2); zero_field!(v2rhosigma); zero_field!(v2rholapl); zero_field!(v2rhotau);
    zero_field!(v2sigma2); zero_field!(v2sigmalapl); zero_field!(v2sigmatau);
    zero_field!(v2lapl2); zero_field!(v2lapltau); zero_field!(v2tau2);
    zero_field!(v3rho3); zero_field!(v3rho2sigma); zero_field!(v3rho2lapl); zero_field!(v3rho2tau);
    zero_field!(v3rhosigma2); zero_field!(v3rhosigmalapl); zero_field!(v3rhosigmatau);
    zero_field!(v3rholapl2); zero_field!(v3rholapltau); zero_field!(v3rhotau2);
    zero_field!(v3sigma3); zero_field!(v3sigma2lapl); zero_field!(v3sigma2tau);
    zero_field!(v3sigmalapl2); zero_field!(v3sigmalapltau); zero_field!(v3sigmatau2);
    zero_field!(v3lapl3); zero_field!(v3lapl2tau); zero_field!(v3lapltau2); zero_field!(v3tau3);
    zero_field!(v4rho4); zero_field!(v4rho3sigma); zero_field!(v4rho3lapl); zero_field!(v4rho3tau);
    zero_field!(v4rho2sigma2); zero_field!(v4rho2sigmalapl); zero_field!(v4rho2sigmatau);
    zero_field!(v4rho2lapl2); zero_field!(v4rho2lapltau); zero_field!(v4rho2tau2);
    zero_field!(v4rhosigma3); zero_field!(v4rhosigma2lapl); zero_field!(v4rhosigma2tau);
    zero_field!(v4rhosigmalapl2); zero_field!(v4rhosigmalapltau); zero_field!(v4rhosigmatau2);
    zero_field!(v4rholapl3); zero_field!(v4rholapl2tau); zero_field!(v4rholapltau2); zero_field!(v4rhotau3);
    zero_field!(v4sigma4); zero_field!(v4sigma3lapl); zero_field!(v4sigma3tau);
    zero_field!(v4sigma2lapl2); zero_field!(v4sigma2lapltau); zero_field!(v4sigma2tau2);
    zero_field!(v4sigmalapl3); zero_field!(v4sigmalapl2tau); zero_field!(v4sigmalapltau2); zero_field!(v4sigmatau3);
    zero_field!(v4lapl4); zero_field!(v4lapl3tau); zero_field!(v4lapl2tau2); zero_field!(v4lapltau3); zero_field!(v4tau4);

    // 3. Reject high-order dispatch early: this layer wires only Exc and Vxc
    // arms for the MGGA family. Fxc/Kxc/Lxc are scoped to a follow-up plan.
    if order >= DerivativeOrder::Fxc {
        return Err(LibxcRsError::UnsupportedDerivativeOrder {
            id: functional.to_id(),
            order,
            max: DerivativeOrder::Vxc,
        });
    }

    // 4. Reject polarized dispatch early: same reason as GGA plan 04-03 deferred
    // D-04-03-A (translated pol kernels have pre-existing bugs).
    if spin != Spin::Unpolarized {
        return Err(LibxcRsError::UnsupportedFunctional {
            id: functional.to_id(),
            reason: "MGGA polarized dispatch deferred pending Phase 4 follow-up \
                     (pol-kernel translation bugs — see deferred-items.md)",
        });
    }

    // 5. Build CubeCL client + input handles (4 inputs).
    let client = cpu_client();
    let rho_handle = create_input_buffer(&client, input.rho());
    let rho_len = input.rho().len();
    let sigma_handle = create_input_buffer(&client, input.sigma());
    let sigma_len = input.sigma().len();
    let lapl_handle = create_input_buffer(&client, input.lapl());
    let lapl_len = input.lapl().len();
    let tau_handle = create_input_buffer(&client, input.tau());
    let tau_len = input.tau().len();

    // 6. Output handle sizing (Exc + Vxc tiers only).
    let zk_len = np * dims.zk as usize;
    let zk_handle = if functional.has_exc() {
        Some(create_zero_output_buffer(&client, zk_len))
    } else {
        None
    };

    let vrho_len = np * dims.vrho as usize;
    let vsigma_len = np * dims.vsigma as usize;
    let vlapl_len = np * dims.vlapl as usize;
    let vtau_len = np * dims.vtau as usize;
    let (vrho_handle, vsigma_handle, vlapl_handle, vtau_handle) =
        if order >= DerivativeOrder::Vxc {
            (
                Some(create_zero_output_buffer(&client, vrho_len)),
                Some(create_zero_output_buffer(&client, vsigma_len)),
                Some(create_zero_output_buffer(&client, vlapl_len)),
                Some(create_zero_output_buffer(&client, vtau_len)),
            )
        } else {
            (None, None, None, None)
        };

    let (cube_count, cube_dim) = calculate_launch_config(np);
    let dt = thresholds.density;
    let zt = thresholds.zeta;

    let ctx = MggaLaunchCtx {
        client: &client,
        cube_count,
        cube_dim,
        rho: &rho_handle,
        rho_len,
        sigma: &sigma_handle,
        sigma_len,
        lapl: &lapl_handle,
        lapl_len,
        tau: &tau_handle,
        tau_len,
        zk: zk_handle.as_ref(),
        zk_len,
        vrho: vrho_handle.as_ref(),
        vrho_len,
        vsigma: vsigma_handle.as_ref(),
        vsigma_len,
        vlapl: vlapl_handle.as_ref(),
        vlapl_len,
        vtau: vtau_handle.as_ref(),
        vtau_len,
        dt,
        zt,
    };

    // 7. Per-functional dispatch — top-level match threads out to the
    // appropriate per-functional submodule under funcs/.
    match functional {

        MggaFunctional::HybMggaXDldf => funcs::hyb_mgga_x_dldf::dispatch_hyb_mgga_x_dldf(&ctx, order, spin)?,
        MggaFunctional::MggaXcZlp => funcs::mgga_xc_zlp::dispatch_mgga_xc_zlp(&ctx, order, spin)?,
        MggaFunctional::MggaCCs => funcs::mgga_c_cs::dispatch_mgga_c_cs(&ctx, order, spin)?,
        MggaFunctional::MggaXLta => funcs::mgga_x_lta::dispatch_mgga_x_lta(&ctx, order, spin)?,
        MggaFunctional::MggaXTpss => funcs::mgga_x_tpss::dispatch_mgga_x_tpss(&ctx, order, spin)?,
        MggaFunctional::MggaXTauHcth => funcs::mgga_x_tau_hcth::dispatch_mgga_x_tau_hcth(&ctx, order, spin)?,
        MggaFunctional::MggaXTb09 => funcs::mgga_x_tb09::dispatch_mgga_x_tb09(&ctx, order, spin)?,
        MggaFunctional::MggaXPkzb => funcs::mgga_x_pkzb::dispatch_mgga_x_pkzb(&ctx, order, spin)?,
        MggaFunctional::MggaXTh => funcs::mgga_x_th::dispatch_mgga_x_th(&ctx, order, spin)?,
        MggaFunctional::MggaXcCc06 => funcs::mgga_xc_cc06::dispatch_mgga_xc_cc06(&ctx, order, spin)?,
        MggaFunctional::MggaXJk => funcs::mgga_x_jk::dispatch_mgga_x_jk(&ctx, order, spin)?,
        MggaFunctional::MggaXMvs => funcs::mgga_x_mvs::dispatch_mgga_x_mvs(&ctx, order, spin)?,
        MggaFunctional::MggaXRtpss => funcs::mgga_x_rtpss::dispatch_mgga_x_rtpss(&ctx, order, spin)?,
        MggaFunctional::MggaCCc => funcs::mgga_c_cc::dispatch_mgga_c_cc(&ctx, order, spin)?,
        MggaFunctional::HybMggaXM05 => funcs::hyb_mgga_x_m05::dispatch_hyb_mgga_x_m05(&ctx, order, spin)?,
        MggaFunctional::MggaXTm => funcs::mgga_x_tm::dispatch_mgga_x_tm(&ctx, order, spin)?,
        MggaFunctional::MggaXcLp90 => funcs::mgga_xc_lp90::dispatch_mgga_xc_lp90(&ctx, order, spin)?,
        MggaFunctional::MggaXGx => funcs::mgga_x_gx::dispatch_mgga_x_gx(&ctx, order, spin)?,
        MggaFunctional::MggaXPbeGx => funcs::mgga_x_pbe_gx::dispatch_mgga_x_pbe_gx(&ctx, order, spin)?,
        MggaFunctional::MggaX2dJs17 => funcs::mgga_x_2d_js17::dispatch_mgga_x_2d_js17(&ctx, order, spin)?,
        MggaFunctional::MggaKRda => funcs::mgga_k_rda::dispatch_mgga_k_rda(&ctx, order, spin)?,
        MggaFunctional::MggaKGea2 => funcs::mgga_k_gea2::dispatch_mgga_k_gea2(&ctx, order, spin)?,
        MggaFunctional::MggaKGea4 => funcs::mgga_k_gea4::dispatch_mgga_k_gea4(&ctx, order, spin)?,
        MggaFunctional::MggaXRlda => funcs::mgga_x_rlda::dispatch_mgga_x_rlda(&ctx, order, spin)?,
        MggaFunctional::MggaXTask => funcs::mgga_x_task::dispatch_mgga_x_task(&ctx, order, spin)?,
    }

    // 8. Read back results from CubeCL buffers into caller-provided slices.
    if let (Some(buf), Some(h)) = (&mut output.zk, zk_handle) {
        let result = read_output_buffer(&client, h, zk_len);
        if buf.len() != result.len() {
            return Err(LibxcRsError::OutputBufferSizeMismatch {
                field: "zk", expected: buf.len(), actual: result.len(),
            });
        }
        buf.copy_from_slice(&result);
    }
    macro_rules! readback { ($field:ident, $handle:expr, $len:expr, $name:literal) => {
        if let (Some(buf), Some(h)) = (&mut output.$field, $handle) {
            let r = read_output_buffer(&client, h, $len);
            if buf.len() != r.len() {
                return Err(LibxcRsError::OutputBufferSizeMismatch {
                    field: $name, expected: buf.len(), actual: r.len(),
                });
            }
            buf.copy_from_slice(&r);
        }
    }; }
    readback!(vrho, vrho_handle, vrho_len, "vrho");
    readback!(vsigma, vsigma_handle, vsigma_len, "vsigma");
    readback!(vlapl, vlapl_handle, vlapl_len, "vlapl");
    readback!(vtau, vtau_handle, vtau_len, "vtau");

    Ok(())
}

