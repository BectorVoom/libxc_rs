//! Per-functional dispatch layer for MGGA kernel evaluation.
//!
//! Routes `dispatch_mgga(functional, ...)` to per-functional launch helpers
//! under `funcs/<func>.rs`, one per routed functional. The outer match in
//! `dispatch_mgga` picks the variant, then delegates to the matching
//! `funcs::<func>::dispatch_<func>` helper. Kernel paths resolve through the
//! `crate::kernel::mgga` per-functional re-export façade (Phase 11 D-10b — no
//! `batchN::` segment survives).
//!
//! **Per-functional scalars (B3 invariant):** Each kernel's `#[cube]`
//! signature is authoritative. For kernels that take zero per-functional
//! scalar args (besides the standard `dens_threshold, zeta_threshold` pair),
//! dispatch wires the unpolarized `Exc` and `Vxc` launches directly. Kernels
//! that take per-functional scalars are listed in the `from_id` match but
//! return `UnsupportedFunctional{...}` at dispatch time.
//!
//! **vxc-only case (`MggaXTb09`):** The `mgga_x_tb09` kernel has no
//! `exc_unpol`/`exc_pol` modules; its signatures omit the `zk` output array.
//! Dispatch rejects `DerivativeOrder::Exc` for this variant.
//!
//! **Derivative order scope:** This dispatch tree wires `Exc` and `Vxc` arms
//! for unpolarized spin only. `Fxc`/`Kxc`/`Lxc` orders and polarized spin
//! mode return `UnsupportedDerivativeOrder` / `UnsupportedFunctional`.
//!
//! Auto-generated by `tools/generate_mgga_dispatch.py` from
//! `.planning/phases/04-bulk-kernel-translation/mgga_roster.tsv`. Do not edit
//! by hand — rerun the generator after roster changes.

