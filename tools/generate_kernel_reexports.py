#!/usr/bin/env python3
"""Generate src/kernel/{lda,gga,mgga}.rs per-functional re-export façade.

Phase 11 D-10b: the per-family façade crates (`libxc_kernel_lda`,
`libxc_kernel_gga`, `libxc_kernel_mgga`) were deleted by D-10a's clean-slate
restructure. The root crate's dispatch tree and `src/eval/dispatch.rs` still
need to resolve `crate::kernel::<family>::<func>::...` paths, so each family
namespace is now a generated module that `pub use`s every per-functional
kernel subcrate in that family.

Each `crates/kernels/<family>/<func>/` directory is a Cargo crate named
`libxc-kernel-<func>` (Rust ident `libxc_kernel_<func>`). This helper emits
`pub use libxc_kernel_<func> as <func>;` for every such subcrate, sorted, so
re-runs are byte-identical (D-LOCK-D idempotency).

`src/kernel/mod.rs` is NOT generated — it is hand-maintained and declares
`pub mod lda; pub mod gga; pub mod mgga;` alongside the other kernel modules.
"""
from __future__ import annotations

from pathlib import Path

WORKSPACE = Path(__file__).resolve().parent.parent
KERNELS_DIR = WORKSPACE / "crates/kernels"
KERNEL_SRC = WORKSPACE / "src/kernel"
FAMILIES = ("lda", "gga", "mgga")


def subcrate_names(family: str) -> list[str]:
    """Sorted list of per-functional subcrate directory names for a family.

    A subcrate directory is any child dir of `crates/kernels/<family>/` that
    contains a `Cargo.toml`.
    """
    family_dir = KERNELS_DIR / family
    names = [
        d.name
        for d in family_dir.iterdir()
        if d.is_dir() and (d / "Cargo.toml").is_file()
    ]
    return sorted(names)


def main() -> None:
    KERNEL_SRC.mkdir(parents=True, exist_ok=True)
    for family in FAMILIES:
        names = subcrate_names(family)
        lines = [
            f"//! {family.upper()} per-functional kernel re-export façade (Phase 11 D-10b).",
            "//!",
            "//! Each per-functional kernel subcrate `libxc-kernel-<func>` is re-exported",
            f"//! under the `crate::kernel::{family}` namespace so dispatch paths",
            f"//! `crate::kernel::{family}::<func>::<output>::...` resolve without a",
            "//! per-family façade crate.",
            "//!",
            "//! Auto-generated by `tools/generate_kernel_reexports.py` — do not hand-edit.",
            "//! Re-runs are deterministic (sorted) for D-LOCK-D idempotency.",
            "",
            "#![allow(unused_imports)]",
            "",
        ]
        for name in names:
            lines.append(f"pub use libxc_kernel_{name} as {name};")
        (KERNEL_SRC / f"{family}.rs").write_text("\n".join(lines) + "\n")
        print(f"wrote src/kernel/{family}.rs — {len(names)} re-exports")


if __name__ == "__main__":
    main()
