def pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def load_roster():
    """Return list of (name, batch, libxc_id, completeness, has_exc, scalars).

    Rows with an `UNKNOWN` libxc id (template kernels not addressed by any
    registry id) and comment lines are skipped — matching the behaviour of
    `generate_gga_dispatch.py`.
    """
    rows = []
    with ROSTER.open() as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) < 6 or parts[2] == "UNKNOWN":
                continue
            name, batch, libxc_id, completeness, has_exc, scalars = parts
            scalars_list = [s for s in scalars.split(",") if s]
            rows.append((name, batch, int(libxc_id), completeness, int(has_exc), scalars_list))
    return rows


