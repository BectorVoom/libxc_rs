#!/usr/bin/env python3
"""Emit `crates/kernels-rayon/math/src/erfcx_coef.rs` from `erfcx_table.rs`.

`erfcx_table.rs::erfcx_y100` is libxc's Faddeeva table as a 100-arm `match`,
one Horner polynomial per arm. The vector form (`simd::erfcx`) needs the same
100 x 7 coefficients as an array it can gather from per lane, so this script
parses them straight out of the scalar table -- the one source the scalar
kernels run -- rather than re-transcribing `faddeeva.c`. The numbers are copied
as spelled, so the two forms parse to identical `f64` constants by
construction.

    python3 tools/translate_rayon/gen_erfcx_coef.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "crates/kernels-rayon/math/src/erfcx_table.rs"
DST = ROOT / "crates/kernels-rayon/math/src/erfcx_coef.rs"

src = SRC.read_text()
cases = re.findall(
    r"(\d+) => \{\s*let t = 2\.0_f64 \* y100 - ([\d.]+)_f64;\s*(.*?)\n\s*\}", src, re.S
)
assert len(cases) == 100, len(cases)
rows = []
for k, off, expr in cases:
    k = int(k)
    assert float(off) == 2 * k + 1, (k, off)
    nums = re.findall(r"(-?[\d.]+e[+-]?\d+)_f64", expr)
    assert len(nums) == 7, (k, len(nums))
    rows.append(nums)

out = [
    "//! `erfcx_y100`'s coefficients as an array, for the vector `simd::erfcx`.",
    "//!",
    "//! GENERATED by `tools/translate_rayon/gen_erfcx_coef.py` from",
    "//! [`crate::erfcx_table`]; do not hand-edit. Row `k` holds `c0..c6` of the",
    "//! arm `k` polynomial `c0 + (c1 + (c2 + (c3 + (c4 + (c5 + c6*t)*t)*t)*t)*t)*t`",
    "//! with `t = 2*y100 - (2k+1)`, spelled exactly as the scalar table spells",
    "//! them, so both forms parse to the same `f64`s.",
    "",
    "/// `[k][j]` = coefficient `c_j` of interval `k`, `k = 0..100`.",
    "pub(crate) static ERFCX_Y100_COEF: [[f64; 7]; 100] = [",
]
for r in rows:
    out.append("    [" + ", ".join(x + "_f64" for x in r) + "],")
out.append("];")
DST.write_text("\n".join(out) + "\n")
print(f"wrote {DST.relative_to(ROOT)}: {len(rows)} rows")
