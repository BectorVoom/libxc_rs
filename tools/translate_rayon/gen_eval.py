#!/usr/bin/env python3
"""Generate the rayon eval layer: per-family sweeps, dispatch, and routing.

Emits into `crates/libxc-reval/src`:

  sweep_<fam>.rs   `<Fam>Chunk` + `split_at` + `par_sweep_<fam>`
  <fam>.rs         `prepare_<fam>` + the `..._dispatch_r<fam>!` macro
  funcs/<func>.rs  one dispatch entry point per functional
  funcs/mod.rs     module list
  routing.rs       functional-enum -> dispatch entry point

and rewrites `crates/libxc-reval/Cargo.toml` with the kernel deps.

Only functionals whose `ext_params` defaults were resolved by
`extract_params.py` are emitted; the rest are listed in `routing.rs` as
explicitly unsupported with the reason, so a caller gets a typed error rather
than silently wrong constants.

Usage: python3 tools/translate_rayon/gen_eval.py
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
KERNELS = REPO / "crates" / "kernels-rayon"
OUT = REPO / "crates" / "libxc-reval" / "src"

FAMILIES = {
    "lda": {
        "inputs": ["rho"],
        "outputs": ["zk", "vrho", "v2rho2", "v3rho3", "v4rho4"],
        "dims": "lda",
    },
    "gga": {
        "inputs": ["rho", "sigma"],
        "outputs": [
            "zk", "vrho", "vsigma", "v2rho2", "v2rhosigma", "v2sigma2",
            "v3rho3", "v3rho2sigma", "v3rhosigma2", "v3sigma3",
            "v4rho4", "v4rho3sigma", "v4rho2sigma2", "v4rhosigma3", "v4sigma4",
        ],
        "dims": "gga",
    },
    "mgga": {
        "inputs": ["rho", "sigma", "lapl", "tau"],
        "outputs": None,  # filled from libxc-core
        "dims": "mgga",
    },
}

# Outputs consumed at each derivative order, cumulatively.
ORDERS = ["Exc", "Vxc", "Fxc", "Kxc", "Lxc"]


def mgga_outputs() -> list[str]:
    s = (REPO / "crates/libxc-core/src/output/mod.rs").read_text()
    m = re.search(r"pub struct MggaOutput<.*?\{(.*?)\n\}", s, re.S)
    return re.findall(r"pub (\w+): Option<", m.group(1))


def order_slices(fam: str, outputs: list[str]) -> dict[str, list[str]]:
    """Which outputs each order writes: everything up to that derivative order."""
    def rank(name: str) -> int:
        if name == "zk":
            return 0
        m = re.match(r"v(\d)", name)
        return int(m.group(1)) if m else 1
    return {o: [f for f in outputs if rank(f) <= i] for i, o in enumerate(ORDERS)}


def gen_sweep(fam: str, inputs: list[str], outputs: list[str]) -> str:
    Fam = fam.capitalize()
    in_fields = "\n".join(f"    pub {n}: &'a [f64]," for n in inputs)
    out_fields = "\n".join(f"    pub {n}: Option<&'a mut [f64]>," for n in outputs)
    in_split = "\n".join(
        f"        let ({n}_l, {n}_r) = self.{n}.split_at(mid * d.{n} as usize);"
        for n in inputs
    )
    out_split = "\n".join(
        f"        let (o{i}_l, o{i}_r) = split_opt(self.{n}, mid * d.{n} as usize);"
        for i, n in enumerate(outputs)
    )
    zero_outs = "\n".join(
        f"    if let Some(s) = chunk.{n}.as_deref_mut() {{ s.fill(0.0); }}"
        for n in outputs
    )
    # One grid point's worth of every output, cleared in place. Used by the
    # fragmented-grid fallback, which lets the kernel run over a below-threshold
    # point and then puts the zero back.
    zero_point_outs = "\n".join(
        f"    if let Some(s) = chunk.{n}.as_deref_mut() {{\n"
        f"        let w = d.{n} as usize;\n"
        f"        s[ip * w..(ip + 1) * w].fill(0.0);\n"
        f"    }}"
        for n in outputs
    )
    win_in = "\n".join(
        f"            {n}: &self.{n}[start * d.{n} as usize..end * d.{n} as usize],"
        for n in inputs
    )
    win_out = "\n".join(
        f"            {n}: self.{n}.as_deref_mut()\n"
        f"                .map(|s| &mut s[start * d.{n} as usize..end * d.{n} as usize]),"
        for n in outputs
    )
    left = ",\n".join(
        [f"                np: mid"]
        + [f"                {n}: {n}_l" for n in inputs]
        + [f"                {n}: o{i}_l" for i, n in enumerate(outputs)]
    )
    right = ",\n".join(
        [f"                np: self.np - mid"]
        + [f"                {n}: {n}_r" for n in inputs]
        + [f"                {n}: o{i}_r" for i, n in enumerate(outputs)]
    )
    return f'''//! Stride-aware parallel splitting for {fam.upper()} evaluations.
//!
//! GENERATED by tools/translate_rayon/gen_eval.py -- do not hand-edit.
//!
//! Each array carries its own elements-per-grid-point count (`Dimensions`), so
//! a run of `n` grid points sits at a *different* offset in every array.
//! Splitting them all at one offset compiles fine and silently misaligns every
//! output past the first chunk, so each is split at its own stride.
//!
//! The split is recursive halving through `rayon::join`, which keeps it in safe
//! code: each worker gets genuinely disjoint `&mut` slices, with no raw
//! pointers anywhere.

use libxc_core::dims::Dimensions;

/// One contiguous run of grid points, every array narrowed to it.
pub struct {Fam}Chunk<'a> {{
    pub np: usize,
{in_fields}
{out_fields}
}}

#[inline]
fn split_opt(o: Option<&mut [f64]>, at: usize) -> (Option<&mut [f64]>, Option<&mut [f64]>) {{
    match o {{
        Some(s) => {{
            let (l, r) = s.split_at_mut(at);
            (Some(l), Some(r))
        }}
        None => (None, None),
    }}
}}

impl<'a> {Fam}Chunk<'a> {{
    /// Split at grid point `mid`, narrowing every array at its own stride.
    pub fn split_at(self, mid: usize, d: &Dimensions) -> ({Fam}Chunk<'a>, {Fam}Chunk<'a>) {{
{in_split}
{out_split}
        (
            {Fam}Chunk {{
{left},
            }},
            {Fam}Chunk {{
{right},
            }},
        )
    }}

    /// Reborrow a contiguous window of `len` grid points starting at `start`.
    ///
    /// `split_at` consumes the chunk, which is what the halving sweep wants but
    /// not what density screening wants: there the same chunk has to be visited
    /// as several disjoint windows and then still be available to clean up
    /// afterwards. Reborrowing keeps ownership with the caller. Every array is
    /// narrowed at its own stride, for the same reason `split_at` is.
    fn window(&mut self, start: usize, len: usize, d: &Dimensions) -> {Fam}Chunk<'_> {{
        let end = start + len;
        {Fam}Chunk {{
            np: len,
{win_in}
{win_out}
        }}
    }}
}}

use std::sync::atomic::{{AtomicUsize, Ordering}};

/// Minimum grid points per task; below this, splitting costs more than it saves.
static MIN_CHUNK: AtomicUsize = AtomicUsize::new(2048);

pub fn min_chunk() -> usize {{
    MIN_CHUNK.load(Ordering::Relaxed)
}}

/// Test hook. Setting this to `usize::MAX` disables splitting, so a dispatch
/// runs as one whole-grid call -- which is exactly the reference the chunked
/// path has to reproduce bit-for-bit.
pub fn set_min_chunk(n: usize) {{
    MIN_CHUNK.store(n.max(1), Ordering::Relaxed);
}}

/// Clear this chunk's slice of every output the sweep is going to write.
///
/// The kernels accumulate with `+=`, so the destination has to start at zero.
/// Doing that in `prepare` instead -- one `fill(0.0)` per whole output array --
/// costs a full serial pass over every output buffer before any arithmetic
/// starts, and leaves the memory cold: by the time the kernel accumulates into
/// a given cache line, the zero written into it has long been evicted, so each
/// element is fetched from DRAM a second time. Per chunk, the zeroed range is
/// still in L1/L2 when the kernel reads it back, and the clearing itself is
/// spread over every worker instead of running on one thread.
///
/// Bit-exactness is unaffected: the stored value and the order of the
/// accumulations are identical either way, only the moment of the store moves.
#[inline]
fn zero_outputs(chunk: &mut {Fam}Chunk<'_>) {{
{zero_outs}
}}

/// Total density at grid point `ip`, the quantity libxc screens on.
#[inline]
fn total_density(rho: &[f64], ip: usize, nc: usize) -> f64 {{
    if nc == 1 {{ rho[ip] }} else {{ rho[ip * 2] + rho[ip * 2 + 1] }}
}}

/// Clear every output at one grid point.
#[inline]
fn zero_point(chunk: &mut {Fam}Chunk<'_>, ip: usize, d: &Dimensions) {{
{zero_point_outs}
}}

/// Average length an above-threshold run must reach before it is worth calling
/// the kernel on it separately.
///
/// Splitting has a fixed per-call cost (the kernel's prologue, and the loop
/// never getting up to speed). Measured on this tree, splitting a grid whose
/// below-threshold points are scattered individually -- average run ~1.7 points
/// -- cost about 14 ns per call, which turned `gga_x_b88` from 1.98 to 6.84
/// ns/point: worse than doing no screening at all. So a fragmented chunk takes
/// the other route below instead.
const MIN_RUN: usize = 64;

/// Evaluate `f` over the above-threshold points only, leaving the rest zero.
///
/// This reproduces what libxc does at the top of its per-point loop
/// (`work_{fam}_inc.c`):
///
/// ```c
/// dens = (nspin == XC_POLARIZED) ? rho[2*ip] + rho[2*ip+1] : rho[ip];
/// if(dens < p->dens_threshold)
///   continue;
/// ```
///
/// **It is a correctness fix before it is an optimisation.** Only some kernels
/// carry a `dens_threshold` guard of their own -- the exchange functionals
/// mostly do (`gga_x_b88`: `rho[ip] / 2.0 <= dens_threshold`), the correlation
/// functionals mostly do not (`lda_c_vwn`, `gga_c_lyp`, `mgga_c_r2scan` have
/// none). libxc puts the screen *outside* the maple2c body, so it covers all of
/// them uniformly; this library called the body directly, so for an unguarded
/// functional the empty tail of a molecular grid got the raw formula value
/// where libxc gives exactly 0. Measured against C libxc on a grid with 40% of
/// its points below threshold, `lda_c_vwn` and `gga_c_lyp` came back with a
/// worst relative difference of 1.0 -- a 100% error on `zk` -- while
/// `gga_x_b88` and `mgga_x_scan`, which have the guard, agreed to 1e-15.
///
/// For a screened point the output keeps the zero `zero_outputs` just wrote.
/// That is bit-identical to what a *guarded* kernel would have produced there
/// (its outputs are `piecewise3(guard, 0.0, ..)` terms, which collapse to
/// `+0.0`), so this changes nothing for those functionals and fixes the rest.
/// Verified: with no below-threshold points present, every output fingerprint
/// is unchanged by this function existing.
///
/// Two routes, picked from a single forward pass over `rho`:
///
/// * **Runs.** A real Becke/Lebedev grid orders points by radial shell, so its
///   empty points are contiguous. Each maximal above-threshold run becomes one
///   kernel call and the tail is never touched -- a whole empty chunk costs
///   nothing at all.
/// * **Compute then re-zero.** If the below-threshold points are scattered so
///   finely that runs would average under `MIN_RUN`, splitting costs more than
///   it saves. Then the kernel runs over the whole chunk and the screened
///   points are zeroed afterwards. No arithmetic is saved, but the answer is
///   the same one, which is the part that matters.
fn screened_call<F>(mut chunk: {Fam}Chunk<'_>, d: &Dimensions, dens_threshold: f64, f: &F)
where
    F: Fn(&mut {Fam}Chunk<'_>) + Sync,
{{
    let nc = d.rho as usize;
    let np = chunk.np;

    // One pass: how many points are screened out, and into how many runs do the
    // survivors fall.
    let mut below = 0usize;
    let mut runs = 0usize;
    let mut prev_active = false;
    for ip in 0..np {{
        let active = total_density(chunk.rho, ip, nc) >= dens_threshold;
        if !active {{
            below += 1;
        }} else if !prev_active {{
            runs += 1;
        }}
        prev_active = active;
    }}

    // Overwhelmingly the common case: nothing to screen, so this costs one
    // linear read of `rho` that the kernel is about to make anyway.
    if below == 0 {{
        f(&mut chunk);
        return;
    }}
    // Whole chunk is in the tail: the zeros already written are the answer.
    if below == np {{
        return;
    }}

    if runs * MIN_RUN <= np - below {{
        let mut ip = 0;
        while ip < np {{
            if total_density(chunk.rho, ip, nc) < dens_threshold {{
                ip += 1;
                continue;
            }}
            let start = ip;
            while ip < np && total_density(chunk.rho, ip, nc) >= dens_threshold {{
                ip += 1;
            }}
            let mut w = chunk.window(start, ip - start, d);
            f(&mut w);
        }}
    }} else {{
        f(&mut chunk);
        for ip in 0..np {{
            if total_density(chunk.rho, ip, nc) < dens_threshold {{
                zero_point(&mut chunk, ip, d);
            }}
        }}
    }}
}}

/// Recursively halve the grid and evaluate each piece in parallel.
pub fn par_sweep<F>(
    mut chunk: {Fam}Chunk<'_>,
    d: &Dimensions,
    min_chunk: usize,
    dens_threshold: f64,
    f: &F,
) where
    F: Fn(&mut {Fam}Chunk<'_>) + Sync,
{{
    if chunk.np <= min_chunk {{
        zero_outputs(&mut chunk);
        screened_call(chunk, d, dens_threshold, f);
        return;
    }}
    let mid = chunk.np / 2;
    let (l, r) = chunk.split_at(mid, d);
    rayon::join(
        || par_sweep(l, d, min_chunk, dens_threshold, f),
        || par_sweep(r, d, min_chunk, dens_threshold, f),
    );
}}
'''


def gen_family(fam: str, inputs: list[str], outputs: list[str]) -> str:
    Fam = fam.capitalize()
    per_order = order_slices(fam, outputs)
    req = "\n".join(
        f'        DerivativeOrder::{o} => &[{", ".join(chr(34)+f+chr(34) for f in fs)}],'
        for o, fs in per_order.items()
    )
    takes = "\n".join(
        f'        {n}: take!({n}, "{n}", d.{n}),' for n in outputs
    )
    in_binds = "\n".join(f"        {n}: input.{n}()," for n in inputs)

    arms = []
    for spin, suf in (("Unpolarized", "u"), ("Polarized", "p")):
        for o in ORDERS:
            fields = "\n".join(
                f'                        c.{f}.as_deref_mut().expect("prepare guarantees this buffer"),'
                for f in per_order[o]
            )
            ins = ", ".join(f"c.{n}" for n in inputs)
            # `$` is literal inside an f-string; `{{`/`}}` are the escaped
            # braces. The metavariable use site must read `$($exc_u)::+` -- the
            # inner `$` is what makes it a metavariable rather than the literal
            # token `exc_u`.
            arms.append(
                f'''            (DerivativeOrder::{o}, Spin::{spin}) => par_sweep(chunk, &d, min_chunk(), dt, &|c: &mut $crate::sweep_{fam}::{Fam}Chunk<'_>| {{
                $(${o.lower()}_{suf})::+(
                        {ins},
{fields}
                        $( $scalar, )*
                        dt, zt,
                    )
            }}),'''
            )
    arms_src = "\n".join(arms)

    kernel_slots = ",\n        ".join(
        f"[$(${o.lower()}_{suf}:tt)::+]"
        for suf in ("u", "p") for o in ORDERS
    )

    return f'''//! {fam.upper()} dispatch over the rayon kernels.
//!
//! GENERATED by tools/translate_rayon/gen_eval.py -- do not hand-edit.

use libxc_core::dims::Dimensions;
use libxc_core::error::LibxcRsError;
use libxc_core::input::{Fam}Input;
use libxc_core::model::DerivativeOrder;
use libxc_core::output::{Fam}Output;

use crate::sweep_{fam}::{Fam}Chunk;

/// Output fields a {fam.upper()} evaluation of `order` must be given.
fn required_fields(order: DerivativeOrder) -> &'static [&'static str] {{
    match order {{
{req}
    }}
}}

/// Validate the caller's buffers and build the chunk view.
///
/// Kernels accumulate with `+=`, so every destination must start at zero --
/// but that zeroing happens per chunk inside `par_sweep`, not here. See the
/// comment on `zero_outputs` for why. Buffers the caller supplied for an order
/// higher than the one requested are still cleared here: they are dropped from
/// the chunk, so the sweep never sees them, and leaving stale values in a
/// buffer the caller handed us would be worse than the cost of clearing it.
pub fn prepare<'a>(
    input: &'a {Fam}Input<'a>,
    output: &'a mut {Fam}Output<'a>,
    order: DerivativeOrder,
    d: &Dimensions,
) -> Result<{Fam}Chunk<'a>, LibxcRsError> {{
    let np = input.np();
    let need = required_fields(order);

    macro_rules! take {{
        ($f:ident, $name:literal, $stride:expr) => {{{{
            let wanted = need.contains(&$name);
            match output.$f.take() {{
                Some(b) if wanted => {{
                    let expected = np * $stride as usize;
                    if b.len() != expected {{
                        return Err(LibxcRsError::OutputBufferSizeMismatch {{
                            field: $name, expected, actual: b.len(),
                        }});
                    }}
                    Some(b)
                }}
                Some(b) => {{ b.fill(0.0); None }}
                None if wanted => {{
                    return Err(LibxcRsError::OutputBufferSizeMismatch {{
                        field: $name, expected: np * $stride as usize, actual: 0,
                    }})
                }}
                None => None,
            }}
        }}}};
    }}

    Ok({Fam}Chunk {{
        np,
{in_binds}
{takes}
    }})
}}

/// Dispatch one {fam.upper()} functional across the grid in parallel.
///
/// Arms are written out rather than folded into a helper macro: `macro_rules!`
/// cannot nest a repetition inside another macro's repetition.
#[macro_export]
macro_rules! ten_arm_dispatch_r{fam} {{
    (
        $input:expr, $output:expr, $order:expr, $spin:expr, $thresholds:expr,
        {kernel_slots},
        params = ( $( $scalar:expr ),* $(,)? )
    ) => {{{{
        use $crate::sweep_{fam}::{{min_chunk, par_sweep}};
        use libxc_core::dims::Dimensions;
        use libxc_core::model::{{DerivativeOrder, Spin}};

        let d = Dimensions::{fam}($spin);
        let dt = $thresholds.density;
        let zt = $thresholds.zeta;
        let chunk = $crate::{fam}::prepare($input, $output, $order, &d)?;

        match ($order, $spin) {{
{arms_src}
        }}
        Ok(())
    }}}};
}}
'''


def gen_func(fam: str, func: str, params: list[str], values: list[str],
             modules: set[str]) -> str | None:
    """One dispatch entry point. Returns None if any of the 10 arms is missing."""
    krate = f"libxc_rkernel_{func}"
    slots = []
    for suf, spin in (("unpol", "u"), ("pol", "p")):
        pass
    for spin_sfx in ("unpol", "pol"):
        for o in ("exc", "vxc", "fxc", "kxc", "lxc"):
            mod = f"{o}_{spin_sfx}"
            if mod not in modules:
                return None
            slots.append(f"        [k::{mod}::{func}_{mod}],")
    def as_f64(v: str) -> str:
        """libxc writes some defaults as integers (`3`); Rust needs a float."""
        return v if ("." in v or "e" in v or "E" in v) else f"{v}.0"

    consts = "\n".join(
        f"/// libxc default for `{p}`.\npub const {p.upper()}: f64 = {as_f64(v)};"
        for p, v in zip(params, values)
    )
    plist = ", ".join(p.upper() for p in params)
    return f'''//! Dispatch for `{func}` over the rayon kernels.
//!
//! GENERATED by tools/translate_rayon/gen_eval.py -- do not hand-edit.
//! Parameter defaults are libxc's `ext_params` values, extracted by
//! tools/translate_rayon/extract_params.py.

use libxc_core::error::LibxcRsError;
use libxc_core::input::{fam.capitalize()}Input;
use libxc_core::model::{{DerivativeOrder, Spin, Thresholds}};
use libxc_core::output::{fam.capitalize()}Output;

use {krate} as k;

{consts}

pub fn dispatch<'a>(
    input: &'a {fam.capitalize()}Input<'a>,
    output: &'a mut {fam.capitalize()}Output<'a>,
    order: DerivativeOrder,
    spin: Spin,
    thresholds: &Thresholds,
) -> Result<(), LibxcRsError> {{
    crate::ten_arm_dispatch_r{fam}!(
        input, output, order, spin, thresholds,
{chr(10).join(slots)}
        params = ({plist})
    )
}}
'''


def main() -> int:
    # The params file used to be a hard-coded path into one session's
    # scratchpad, which stopped existing the moment that session ended and
    # took the whole regen pipeline with it. Default it next to this script
    # and let the caller override.
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--params",
        type=Path,
        default=REPO / "tools" / "translate_rayon" / "params.json",
        help="extract_params.py --json output (default: %(default)s)",
    )
    args = ap.parse_args()
    pj = args.params
    if not pj.is_file():
        print(
            f"missing {pj}\nrun: python3 tools/translate_rayon/extract_params.py "
            f"--json {pj}",
            file=sys.stderr,
        )
        return 2
    data = json.loads(pj.read_text())
    resolved, unresolved = data["resolved"], data["unresolved"]

    FAMILIES["mgga"]["outputs"] = mgga_outputs()

    (OUT / "funcs").mkdir(parents=True, exist_ok=True)

    for fam, spec in FAMILIES.items():
        (OUT / f"sweep_{fam}.rs").write_text(
            gen_sweep(fam, spec["inputs"], spec["outputs"]))
        (OUT / f"{fam}.rs").write_text(
            gen_family(fam, spec["inputs"], spec["outputs"]))

    emitted, skipped = [], dict(unresolved)
    for func, info in sorted(resolved.items()):
        fam = info["family"]
        srcdir = KERNELS / fam / func / "src"
        modules = {p.stem for p in srcdir.glob("*.rs")} | {
            p.name for p in srcdir.iterdir() if p.is_dir()}
        text = gen_func(fam, func, info["params"], info["values"], modules)
        if text is None:
            skipped[func] = "kernel tree is missing one of the 10 (order, spin) modules"
            continue
        (OUT / "funcs" / f"{func}.rs").write_text(text)
        emitted.append((fam, func))

    (OUT / "funcs" / "mod.rs").write_text(
        "//! Per-functional dispatch entry points.\n"
        "//!\n//! GENERATED by tools/translate_rayon/gen_eval.py -- do not hand-edit.\n\n"
        + "\n".join(f'#[cfg(feature = "{f}")]\npub mod {f};' for _, f in emitted)
        + "\n")

    lines = [
        "//! Functional -> dispatch entry point.",
        "//!",
        "//! GENERATED by tools/translate_rayon/gen_eval.py -- do not hand-edit.",
        "//!",
        "//! Functionals whose libxc `ext_params` defaults could not be resolved",
        "//! mechanically are listed in `UNSUPPORTED` with the reason. They return a",
        "//! typed error rather than running with guessed constants.",
        "",
        "/// (functional, why it is not wired)",
        "pub const UNSUPPORTED: &[(&str, &str)] = &[",
    ]
    # json.dumps gives a correctly escaped double-quoted literal, which is what
    # Rust wants. The reasons quote C source, so they contain `"` themselves --
    # a naive quote swap produces `["0.95*KINX", ...]` inside a string literal
    # and rustc reads `KINX` as an unknown literal prefix.
    for func, why in sorted(skipped.items()):
        lines.append(f"    ({json.dumps(func)}, {json.dumps(why)}),")
    lines += ["];", "",
              "/// Functionals wired to a rayon kernel, by family.",
              "pub const SUPPORTED: &[(&str, &str)] = &["]
    for fam, func in emitted:
        lines.append(f'    ("{fam}", "{func}"),')
    lines += ["];", ""]

    for fam in ("lda", "gga", "mgga"):
        Fam = fam.capitalize()
        fam_funcs = [f for g, f in emitted if g == fam]
        arms = "\n".join(
            f'        "{f}" => Some(crate::funcs::{f}::dispatch('
            f'input, output, order, spin, thresholds)),'
            for f in fam_funcs
        )
        lines += [
            f"/// Dispatch a {fam.upper()} functional by libxc name.",
            "///",
            "/// Returns `None` when the functional is not wired -- see `UNSUPPORTED`",
            "/// for why. `None` rather than an error because building an",
            "/// `UnsupportedFunctional` needs a `FunctionalId`, which a name lookup",
            "/// does not have; the caller knows its own id and can raise it.",
            f"pub fn dispatch_{fam}_by_name<'a>(",
            "    name: &str,",
            f"    input: &'a libxc_core::input::{Fam}Input<'a>,",
            f"    output: &'a mut libxc_core::output::{Fam}Output<'a>,",
            "    order: libxc_core::model::DerivativeOrder,",
            "    spin: libxc_core::model::Spin,",
            "    thresholds: &libxc_core::model::Thresholds,",
            ") -> Option<Result<(), libxc_core::error::LibxcRsError>> {",
            "    match name {",
            arms,
            "        _ => None,",
            "    }",
            "}",
            "",
        ]

    # --- typed (enum) dispatch -------------------------------------------
    # The facade and C-ABI take a `<Fam>Functional` enum, not a name. The enums
    # cover only 168 of the 305 functionals in the kernel tree, so this is a
    # partial view by construction: variants with no wired kernel return
    # UnsupportedFunctional, which is the honest answer and carries the id the
    # caller needs.
    import re as _re
    enum_variants = {}
    for fam_, file_ in (("lda", "lda_functional.rs"), ("gga", "gga_functional.rs"),
                        ("mgga", "mgga_functional.rs")):
        src_ = (REPO / "crates/libxc-core/src/model" / file_).read_text()
        m_ = _re.search(r"pub enum \w+Functional\s*\{(.*?)\n\}", src_, _re.S)
        enum_variants[fam_] = set(_re.findall(r"^\s{4}([A-Z]\w*)\s*,", m_.group(1), _re.M))

    def pascal(n: str) -> str:
        return "".join(part.capitalize() for part in n.split("_"))

    for fam in ("lda", "gga", "mgga"):
        Fam = fam.capitalize()
        wired = [f for g, f in emitted if g == fam]
        typed = [f for f in wired if pascal(f) in enum_variants[fam]]
        arms = "\n".join(
            f"        {Fam}Functional::{pascal(f)} => "
            f'crate::funcs::{f}::dispatch(input, output, order, spin, thresholds),'
            for f in typed
        )
        lines += [
            f"/// Dispatch a {fam.upper()} functional by enum -- the typed entry point the",
            "/// facade and C-ABI use.",
            "///",
            f"/// {len(typed)} of the {len(wired)} wired {fam.upper()} functionals have an enum",
            "/// variant; the rest are reachable only by name. Variants with no wired",
            "/// kernel return `UnsupportedFunctional` carrying their own id.",
            f"pub fn dispatch_{fam}<'a>(",
            f"    functional: libxc_core::model::{Fam}Functional,",
            f"    input: &'a libxc_core::input::{Fam}Input<'a>,",
            f"    output: &'a mut libxc_core::output::{Fam}Output<'a>,",
            "    order: libxc_core::model::DerivativeOrder,",
            "    spin: libxc_core::model::Spin,",
            "    thresholds: &libxc_core::model::Thresholds,",
            ") -> Result<(), libxc_core::error::LibxcRsError> {",
            f"    use libxc_core::model::{Fam}Functional;",
            "    match functional {",
            arms,
            "        other => Err(libxc_core::error::LibxcRsError::UnsupportedFunctional {",
            "            id: other.to_id(),",
            '            reason: "not wired to a rayon kernel; see routing::UNSUPPORTED",',
            "        }),",
            "    }",
            "}",
            "",
        ]

    (OUT / "routing.rs").write_text("\n".join(lines))

    # Cargo.toml: one optional dep + feature per wired functional.
    deps = "\n".join(
        f'libxc-rkernel-{f} = {{ path = "../kernels-rayon/{fam}/{f}", optional = true }}'
        for fam, f in emitted)
    feats = "\n".join(f'{f} = ["dep:libxc-rkernel-{f}"]' for _, f in emitted)
    default = ", ".join(f'"{f}"' for _, f in emitted)
    (REPO / "crates/libxc-reval/Cargo.toml").write_text(f'''[package]
name = "libxc-reval"
version = "0.1.0"
edition = "2024"

[dependencies]
libxc-core = {{ path = "../libxc-core" }}
rayon = "1.11"
{deps}

[features]
default = [{default}]
{feats}
''')

    (OUT / "lib.rs").write_text('''//! Rayon evaluation layer.
//!
//! Calls the plain-Rust kernels in `crates/kernels-rayon` directly on the
//! caller's slices, parallelised over grid points. No device buffers, no
//! upload/launch/read-back cycle.

pub mod funcs;
pub mod gga;
pub mod lda;
pub mod mgga;
pub mod routing;
pub mod sweep_gga;
pub mod sweep_lda;
pub mod sweep_mgga;
''')

    by_fam = {}
    for fam, f in emitted:
        by_fam[fam] = by_fam.get(fam, 0) + 1
    print(f"emitted {len(emitted)} functionals: " +
          ", ".join(f"{k}={v}" for k, v in sorted(by_fam.items())))
    print(f"skipped {len(skipped)} (listed in routing.rs UNSUPPORTED)")
    return 0


