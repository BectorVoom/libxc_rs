"""Generate the rayon eval layer: per-family sweeps, dispatch, and routing.

Emits into `crates/libxc-reval/src`:

  sweep_<fam>.rs   `<Fam>Chunk` + `split_at` + `par_sweep_<fam>`
  <fam>.rs         `prepare_<fam>` + the `..._dispatch_r<fam>!` macro
  funcs/<func>.rs  one dispatch entry point per functional
  funcs/mod.rs     module list
  routing.rs       functional-enum -> dispatch entry point

and rewrites `crates/libxc-reval/Cargo.toml` with the kernel deps.

Only functionals whose `ext_params` defaults were resolved by
`extract_params.py` are emitted; the rest are listed in `routing.rs` as
explicitly unsupported with the reason, so a caller gets a typed error rather
than silently wrong constants.

Usage: python3 tools/translate_rayon/gen_eval.py
"""
