//! Generator and gate: libxc's deorbitalized functionals, and where their
//! ext_params go.
//!
//! Without arguments this checks that
//! `crates/libxc-core/src/meta/generated_deorbitalized.rs` is still what libxc
//! says. With `LIBXC_RS_WRITE_DEORBITALIZED=1` it rewrites the file:
//!
//! ```text
//! LIBXC_RS_WRITE_DEORBITALIZED=1 cargo test \
//!     --manifest-path verify/Cargo.toml --test gen_deorbitalized
//! ```
//!
//! # Why this is read out of libxc rather than out of its C
//!
//! libxc builds SCAN-L and its relatives with `xc_deorbitalize_init(p, base,
//! ked)` -- an init call, not an `xc_mix_init` -- so the metadata snapshot
//! records no auxiliaries for them. Like `gen_aux_overrides.rs`, this reads
//! the answer out of libxc's own `xc_func_type` after `xc_func_init`: a
//! deorbitalized functional is one with two auxiliaries and no mix
//! coefficients (`n_func_aux == 2`, `mix_coef == NULL`), `func_aux[0]` is the
//! base meta-GGA and `func_aux[1]` the kinetic-energy functional that stands
//! in for `tau`.
//!
//! Where each parent ext_param lands is observed the same way: set the
//! parent's ext_params to distinct sentinels through libxc's own setter and
//! record which auxiliary holds each one, at which index. A setter that
//! transformed a value instead of copying it would leave a sentinel nowhere,
//! and this fails rather than describe it as a copy.

use std::path::PathBuf;

use libxc_rs::registry::all_functional_ids;
use libxc_sys::{xc_func_end, xc_func_init, xc_func_set_ext_params, xc_func_type, XC_UNPOLARIZED};

struct Row {
    id: u16,
    base: u16,
    ked: u16,
    /// Per parent ext_param: `(aux slot, index in that auxiliary's ext_params)`.
    map: Vec<(u8, u8)>,
}

fn row_for(id: u16) -> Option<Row> {
    let mut t: xc_func_type = unsafe { std::mem::zeroed() };
    if unsafe { xc_func_init(&mut t, id as i32, XC_UNPOLARIZED as i32) } != 0 {
        return None;
    }
    let row = unsafe { inspect(&mut t, id) };
    unsafe { xc_func_end(&mut t) };
    row
}

/// # Safety
/// `t` must be a functional `xc_func_init` initialised successfully.
unsafe fn inspect(t: &mut xc_func_type, id: u16) -> Option<Row> {
    unsafe {
        if t.n_func_aux != 2 || !t.mix_coef.is_null() {
            return None;
        }
        let func_aux = t.func_aux;
        let aux = |i: usize| *func_aux.add(i);
        let base = (*(*aux(0)).info).number as u16;
        let ked = (*(*aux(1)).info).number as u16;

        let n = (*t.info).ext_params.n as usize;
        let mut map = Vec::with_capacity(n);
        if n > 0 {
            let defaults: Vec<f64> = (0..n).map(|k| *(*t.info).ext_params.values.add(k)).collect();
            // Distinct, exactly representable, and far from every default.
            let sentinels: Vec<f64> = (0..n).map(|k| 1000.0 + 0.125 * k as f64).collect();
            xc_func_set_ext_params(t, sentinels.as_ptr());
            for (j, s) in sentinels.iter().enumerate() {
                let mut hit = None;
                for slot in 0..2usize {
                    let a = aux(slot);
                    if (*a).ext_params.is_null() {
                        continue;
                    }
                    for k in 0..(*(*a).info).ext_params.n as usize {
                        if *(*a).ext_params.add(k) == *s {
                            assert!(hit.is_none(), "functional {id}: ext_param {j} lands twice");
                            hit = Some((slot as u8, k as u8));
                        }
                    }
                }
                map.push(hit.unwrap_or_else(|| {
                    panic!(
                        "functional {id}: ext_param {j} lands on no auxiliary -- its setter \
                         transforms the value, and a copy map cannot describe that"
                    )
                }));
            }
            xc_func_set_ext_params(t, defaults.as_ptr());
        }
        Some(Row { id, base, ked, map })
    }
}

fn render(rows: &[Row]) -> String {
    let mut s = String::from(
        "//! libxc's deorbitalized meta-GGAs: base functional, kinetic-energy\n\
         //! functional, and where each parent ext_param goes.\n\
         //!\n\
         //! GENERATED by `verify/tests/gen_deorbitalized.rs` from libxc's own\n\
         //! `xc_func_type` -- do not hand-edit. Regenerate with:\n\
         //!\n\
         //! ```text\n\
         //! LIBXC_RS_WRITE_DEORBITALIZED=1 cargo test \\\n\
         //!     --manifest-path verify/Cargo.toml --test gen_deorbitalized\n\
         //! ```\n\
         #![allow(clippy::all)]\n\
         \n\
         use super::Deorbitalized;\n\
         use crate::model::FunctionalId;\n\
         \n\
         pub static DEORBITALIZED: &[Deorbitalized] = &[\n",
    );
    for r in rows {
        let map: Vec<String> = r.map.iter().map(|(a, k)| format!("({a}, {k})")).collect();
        s.push_str(&format!(
            "    Deorbitalized {{ id: FunctionalId({}), base: FunctionalId({}), ked: FunctionalId({}), \
             ext_to_aux: &[{}] }},\n",
            r.id,
            r.base,
            r.ked,
            map.join(", ")
        ));
    }
    s.push_str("];\n");
    s
}

#[test]
fn deorbitalized_table_matches_libxc() {
    let rows: Vec<Row> = all_functional_ids().filter_map(|id| row_for(id.raw())).collect();
    for r in &rows {
        println!("{} <- base {} + ked {}, ext_to_aux {:?}", r.id, r.base, r.ked, r.map);
    }
    assert!(!rows.is_empty(), "libxc reports no deorbitalized functional at all");
    let text = render(&rows);
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../crates/libxc-core/src/meta/generated_deorbitalized.rs");
    if std::env::var_os("LIBXC_RS_WRITE_DEORBITALIZED").is_some() {
        std::fs::write(&path, &text).expect("write table");
        println!("wrote {}", path.display());
    } else {
        let on_disk = std::fs::read_to_string(&path).unwrap_or_default();
        assert_eq!(
            on_disk, text,
            "generated_deorbitalized.rs is not what libxc reports; regenerate with \
             LIBXC_RS_WRITE_DEORBITALIZED=1"
        );
    }
}
