#!/usr/bin/env python3
"""Generate the buffer/launch glue for the MGGA benchmark.

Reads the transliterated native kernel, recovers each array's per-grid-point
stride from its `ip * K + J` access pattern, and emits a module with:
  * `Bufs`      — host-side buffers, one Vec<f64> per array, correctly sized
  * `run_native_range` / `run_native_rayon`
  * `upload` / `launch` / `sync`-able CubeCL handles

Usage: gen_mgga_glue.py <native.rs> <fn_name> <out.rs>
"""
import re
import sys

INPUTS = ("rho", "sigma", "lapl", "tau")


def main() -> None:
    native_path, fn_name, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    src = open(native_path).read()

    sig = re.search(r"pub unsafe fn \w+_range\(\n(.*?)\n\) \{", src, re.S).group(1)
    arrays, scalars = [], []
    for line in sig.split("\n"):
        line = line.strip().rstrip(",")
        if not line:
            continue
        name, ty = (x.strip() for x in line.split(":", 1))
        if name in ("lo", "hi"):
            continue
        if ty.endswith("f64") and ty.startswith("*"):
            arrays.append((name, ty == "*const f64"))
        elif ty == "f64":
            scalars.append(name)

    # Recover strides from the access patterns.
    # NB: the leading lookbehind is essential — without it `sigma.add(...)`
    # also matches the tail of `v2rhosigma.add(...)` and inflates the stride.
    stride = {}
    for name, _ in arrays:
        pre = r"(?<![A-Za-z0-9_])" + re.escape(name)
        ks = [int(k) for k in re.findall(pre + r"\.add\(ip \* (\d+)", src)]
        if re.search(pre + r"\.add\(ip\)", src):
            ks.append(1)
        stride[name] = max(ks) if ks else 1

    out_arms = "\n".join(
        f'            "{n}" => &mut self.{n},' for n, is_in in arrays if not is_in
    )

    fields = "\n".join(f"    pub {n}: Vec<f64>," for n, _ in arrays)
    inits = "\n".join(f"            {n}: vec![0.0; n * {stride[n]}]," for n, _ in arrays)
    strides = "\n".join(f'    ("{n}", {stride[n]}),' for n, _ in arrays)

    native_args = ",\n            ".join(
        (f"b.{n}.as_ptr()" if is_in else f"b.{n}.as_mut_ptr()") for n, is_in in arrays
    )
    native_args_ptr = ",\n            ".join(
        (f"p.{n} as *const f64" if is_in else f"p.{n}") for n, is_in in arrays
    )
    scalar_args = ",\n            ".join(f"s.{n}" for n in scalars)
    scalar_fields = "\n".join(f"    pub {n}: f64," for n in scalars)

    ptr_fields = "\n".join(f"    pub {n}: *mut f64," for n, _ in arrays)
    ptr_inits = "\n".join(
        f"            {n}: self.{n}.as_mut_ptr()," for n, _ in arrays
    )

    handle_fields = "\n".join(f"    pub {n}: Handle," for n, _ in arrays)
    handle_inits = "\n".join(
        f"            {n}: client.create_from_slice(bytemuck::cast_slice(&b.{n}))," for n, _ in arrays
    )
    launch_args = ",\n            ".join(
        f"ArrayArg::from_raw_parts(h.{n}.clone(), n * {stride[n]})" for n, _ in arrays
    )

    out = f'''//! Buffer + launch glue for the MGGA benchmark.
//!
//! GENERATED by xcbench/gen_mgga_glue.py — do not hand-edit.

#![allow(non_snake_case, clippy::too_many_arguments)]

use cubecl::client::ComputeClient;
use cubecl::prelude::*;
use cubecl::server::Handle;

use crate::mgga_native::{fn_name}_range;
use libxc_kernel_mgga_x_tpss::kxc_pol::{fn_name};

/// (array name, elements per grid point)
pub const STRIDES: &[(&str, usize)] = &[
{strides}
];

#[derive(Clone, Copy)]
pub struct Params {{
{scalar_fields}
}}

pub struct Bufs {{
{fields}
    pub n: usize,
}}

/// Raw pointers to a `Bufs`, so rayon workers can take disjoint ip-ranges.
#[derive(Clone, Copy)]
pub struct Ptrs {{
{ptr_fields}
}}
unsafe impl Send for Ptrs {{}}
unsafe impl Sync for Ptrs {{}}

impl Bufs {{
    pub fn new(n: usize) -> Self {{
        Bufs {{
{inits}
            n,
        }}
    }}

    pub fn ptrs(&mut self) -> Ptrs {{
        Ptrs {{
{ptr_inits}
        }}
    }}

    pub fn total_elems(&self) -> usize {{
        STRIDES.iter().map(|(_, k)| k * self.n).sum()
    }}

    /// Mutable access to an output buffer by name.
    pub fn output_mut(&mut self, name: &str) -> &mut Vec<f64> {{
        match name {{
{out_arms}
            _ => panic!("unknown output array {{name}}"),
        }}
    }}
}}

pub fn read<R: Runtime>(client: &ComputeClient<R>, h: &Handle) -> Vec<f64> {{
    let bytes = client.read_one(h.clone()).expect("readback failed");
    bytemuck::cast_slice(&bytes).to_vec()
}}

/// Single-threaded native sweep.
pub fn run_native_serial(b: &mut Bufs, s: &Params) {{
    let n = b.n;
    unsafe {{
        {fn_name}_range(
            {native_args},
            {scalar_args},
            0,
            n,
        );
    }}
}}

/// Rayon-parallel native sweep over disjoint ip-ranges.
pub fn run_native_rayon(p: Ptrs, s: &Params, n: usize, chunk: usize) {{
    use rayon::prelude::*;
    let nchunks = n.div_ceil(chunk);
    (0..nchunks).into_par_iter().for_each(|c| {{
        let lo = c * chunk;
        let hi = ((c + 1) * chunk).min(n);
        unsafe {{
            {fn_name}_range(
                {native_args_ptr},
                {scalar_args},
                lo,
                hi,
            );
        }}
    }});
}}

pub struct DeviceBufs {{
{handle_fields}
}}

pub fn upload<R: Runtime>(client: &ComputeClient<R>, b: &Bufs) -> DeviceBufs {{
    DeviceBufs {{
{handle_inits}
    }}
}}

pub fn launch<R: Runtime>(
    client: &ComputeClient<R>,
    h: &DeviceBufs,
    n: usize,
    s: &Params,
    workgroup: u32,
) {{
    let count = CubeCount::new_1d((n as u32).div_ceil(workgroup));
    let dim = CubeDim::new_1d(workgroup);
    unsafe {{
        {fn_name}::launch_unchecked::<R>(
            client,
            count,
            dim,
            {launch_args},
            {scalar_args},
        );
    }}
}}
'''
    open(out_path, "w").write(out)
    print(f"wrote {out_path}: {len(arrays)} arrays, {len(scalars)} scalars")
    print("strides:", {n: stride[n] for n, _ in arrays})


if __name__ == "__main__":
    main()
