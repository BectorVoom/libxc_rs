#!/usr/bin/env python3
"""Mechanically convert a `#[cube]` kernel file into an equivalent plain-Rust fn.

The generated code keeps the maple2c variable names and the exact floating-point
operation order, so the native leg and the CubeCL leg differ only in *how* the
arithmetic is scheduled, never in *what* arithmetic is done.

Transformations:
  * drop the `#[cube(...)]` / cubecl imports
  * `&Array<f64>` / `&mut Array<f64>`  ->  raw `*const f64` / `*mut f64`
    (CubeCL kernels launched with `launch_unchecked` do no bounds checking, so
    raw pointers are the like-for-like native form)
  * `name[expr]`                       ->  `(*name.add(expr))`
  * `let ip = ABSOLUTE_POS; if ip < zk.len() { .. }`  ->  `for ip in lo..hi { .. }`
  * `piecewise3::<f64>` / `pow_1_3::<f64>` -> native helpers

Usage: transliterate.py <kernel.rs> <fn_name> <out.rs>
"""
import re
import sys


def main() -> None:
    src_path, fn_name, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    src = open(src_path).read()

    # ---- signature ------------------------------------------------------
    m = re.search(r"pub fn " + re.escape(fn_name) + r"\(\n(.*?)\n\) \{", src, re.S)
    if not m:
        sys.exit(f"could not find signature of {fn_name} in {src_path}")
    sig_body = m.group(1)

    params = []          # (name, rust_type)
    arrays = []          # array param names, in order
    for line in sig_body.split("\n"):
        line = line.strip().rstrip(",")
        if not line:
            continue
        name, ty = line.split(":", 1)
        name, ty = name.strip(), ty.strip()
        if ty == "&Array<f64>":
            params.append((name, "*const f64"))
            arrays.append(name)
        elif ty == "&mut Array<f64>":
            params.append((name, "*mut f64"))
            arrays.append(name)
        elif ty == "f64":
            params.append((name, "f64"))
        else:
            sys.exit(f"unhandled param type: {name}: {ty}")

    # ---- body -----------------------------------------------------------
    body_start = src.index("let ip = ABSOLUTE_POS;")
    guard = re.compile(r"if ip < \w+\.len\(\) \{")
    gm = guard.search(src, body_start)
    if not gm:
        sys.exit("could not find the `if ip < ...len()` guard")
    inner = src[gm.end():]
    # Trim the two closing braces that end the guard and the fn.
    inner = inner.rstrip()
    assert inner.endswith("}"), "unexpected file tail"
    inner = inner[:-1].rstrip()          # closes fn
    assert inner.endswith("}"), "unexpected guard tail"
    inner = inner[:-1].rstrip()          # closes guard

    # `name[expr]` -> `(*name.add(expr))`, only for the array params.
    arr_alt = "|".join(sorted(map(re.escape, arrays), key=len, reverse=True))
    inner = re.sub(
        r"\b(" + arr_alt + r")\[([^\[\]]*)\]",
        lambda mo: f"(*{mo.group(1)}.add({mo.group(2)}))",
        inner,
    )

    # CubeCL generic helpers -> native helpers.
    inner = re.sub(r"\b(piecewise3|piecewise5|pow_1_3|pow_2_3|pow_4_3|Heaviside)::<f64>", r"\1", inner)

    # ---- emit -----------------------------------------------------------
    plist = ",\n    ".join(f"{n}: {t}" for n, t in params)
    used_helpers = sorted(
        h for h in ("piecewise3", "piecewise5", "pow_1_3", "pow_2_3", "pow_4_3", "Heaviside")
        if re.search(r"\b" + h + r"\b", inner)
    )
    used_consts = sorted(
        c for c in ("M_CBRT2", "M_CBRT3", "M_CBRT6", "M_CBRTPI", "M_PI")
        if re.search(r"\b" + c + r"\b", inner)
    )
    imports = ", ".join(used_helpers + used_consts)

    out = f'''//! Plain-Rust transliteration of `{fn_name}`.
//!
//! GENERATED by xcbench/transliterate.py from
//! `{src_path}` — do not hand-edit.
//!
//! Same maple2c variable names, same floating-point operation order, no bounds
//! checks (matching `launch_unchecked` semantics on the CubeCL side).

#![allow(non_snake_case, unused_variables, unused_parens, clippy::excessive_precision, clippy::too_many_arguments, clippy::needless_return)]

use crate::native::{{{imports}}};

/// Evaluate grid points `lo..hi`.
///
/// # Safety
/// All pointers must be valid for the strided accesses performed over
/// `lo..hi`, and concurrent calls must be given disjoint `lo..hi` ranges.
pub unsafe fn {fn_name}_range(
    {plist},
    lo: usize,
    hi: usize,
) {{
    for ip in lo..hi {{ unsafe {{
{inner}
    }} }}
}}
'''
    open(out_path, "w").write(out)
    n_arr = len(arrays)
    n_scalar = len(params) - n_arr
    print(f"wrote {out_path}: {n_arr} arrays, {n_scalar} scalars, {inner.count(chr(10)) + 1} body lines")


if __name__ == "__main__":
    main()
