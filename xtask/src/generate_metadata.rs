fn write_generated_rs(root: &Path, functionals: &[SnapshotMeta]) -> Result<()> {
    let path = root.join("src/meta/generated.rs");
    
    let mut content = String::from(
        "//! Auto-generated by xtask generate-metadata. DO NOT EDIT.\n\
         #![allow(non_upper_case_globals)]\n\n\
         use crate::model::{DerivativeOrder, Family, FunctionalFlags, FunctionalId, HybridTermKind, HybridType, Kind};\n\
         use crate::meta::{ExtParamSpec, FunctionalMeta, HybridTerm, Reference};\n\n"
    );
    
    // Write one const per functional (currently empty, would be populated by full impl)
    for func in functionals {
        content.push_str(&format!(
            "pub(crate) const FUNC_{}: FunctionalMeta = FunctionalMeta {{\
             \n    id: FunctionalId({}),\
             \n    name: \"{}\",\
             \n    // ... populated by full implementation\
             \n}};\n\n",
            func.name.to_uppercase(), func.id, func.name
        ));
    }
    
    fs::write(&path, content)
        .map_err(|e| anyhow!("Failed to write {}: {}", path.display(), e))
}

